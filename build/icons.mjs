#!/usr/bin/env node
/* =========================================================================
   Generates content/icons.js from the installed @tabler/icons package.

   Extension UI cannot pull an icon font or an npm icon component at runtime,
   and emoji glyphs (🗑 ⬇ ⏸) render differently on every platform — on Linux
   they depend entirely on which emoji font happens to be installed. So the
   handful of glyphs actually used are vendored as path data at build time.

     node build/icons.mjs
   ========================================================================= */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = path.join(root, 'node_modules', '@tabler', 'icons', 'icons');

// name in our code -> [variant, tabler file]
const WANTED = {
  prev: ['filled', 'player-skip-back'],
  play: ['filled', 'player-play'],
  pause: ['filled', 'player-pause'],
  stop: ['filled', 'player-stop'],
  next: ['filled', 'player-skip-forward'],
  close: ['outline', 'x'],
  trash: ['outline', 'trash'],
  download: ['outline', 'download'],
  settings: ['outline', 'settings'],
  check: ['outline', 'check'],
  broom: ['outline', 'wash-machine'],
  speaker: ['outline', 'volume'],
  voice: ['outline', 'microphone-2'],
  speed: ['outline', 'brand-speedtest'],
  grip: ['outline', 'grip-horizontal']
};

if (!fs.existsSync(iconsDir)) {
  throw new Error('@tabler/icons not installed — run `npm install --no-save @tabler/icons` first.');
}

const icons = {};
for (const [name, [variant, file]] of Object.entries(WANTED)) {
  const source = path.join(iconsDir, variant, `${file}.svg`);
  if (!fs.existsSync(source)) {
    console.warn(`skip     ${name} (${variant}/${file}.svg not found)`);
    continue;
  }
  const svg = fs.readFileSync(source, 'utf8');

  // Keep only the drawing instructions; the wrapper <svg> is rebuilt at
  // runtime so every icon inherits size and currentColor consistently.
  const inner = svg
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  icons[name] = { inner, filled: variant === 'filled' };
  console.log(`icon     ${name.padEnd(9)} <- ${variant}/${file}.svg`);
}

const header = `/* =========================================================================
   Icon set — generated by build/icons.mjs, do not edit by hand.

   Path data from Tabler Icons (https://tabler.io/icons), MIT License,
   Copyright (c) 2020-2026 Paweł Kuna.

   Icons are built as real SVG nodes rather than emoji so they inherit
   currentColor and size predictably on every platform.
   ========================================================================= */

(() => {
  'use strict';
  const NS = (globalThis.TTSFlow = globalThis.TTSFlow || {});
  if (NS.icon) return;

  const PATHS = ${JSON.stringify(icons, null, 2)};

  const SVG_NS = 'http://www.w3.org/2000/svg';

  // size is applied via CSS (width/height: 1em) so icons track font-size.
  NS.icon = function icon(name, { size = 18, className = '' } = {}) {
    const spec = PATHS[name];
    const svg = document.createElementNS(SVG_NS, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', String(size));
    svg.setAttribute('height', String(size));
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    if (className) svg.setAttribute('class', className);

    if (!spec) return svg;

    if (spec.filled) {
      svg.setAttribute('fill', 'currentColor');
      svg.setAttribute('stroke', 'none');
    } else {
      svg.setAttribute('fill', 'none');
      svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', '1.75');
      svg.setAttribute('stroke-linecap', 'round');
      svg.setAttribute('stroke-linejoin', 'round');
    }

    // Parsed rather than assigned as innerHTML: the source is generated
    // build output, but parsing keeps this free of markup assignment.
    const parsed = new DOMParser().parseFromString(
      \`<svg xmlns="\${SVG_NS}">\${spec.inner}</svg>\`,
      'image/svg+xml'
    );
    for (const child of Array.from(parsed.documentElement.childNodes)) {
      svg.appendChild(child);
    }
    return svg;
  };
})();
`;

fs.writeFileSync(path.join(root, 'content', 'icons.js'), header);
console.log(`\nwrote    content/icons.js (${Object.keys(icons).length} icons)`);
